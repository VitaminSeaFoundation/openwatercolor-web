#!/usr/bin/env node
/*
 * Builds every target from the shared sources. No dependencies beyond Node 18+ (and the `zip` CLI for xhs).
 *
 *   node scripts/build.mjs            all targets whose sources are present
 *   node scripts/build.mjs web        dist/web/   static site for independent hosting
 *   node scripts/build.mjs xhs        dist/xhs/ + dist/underwater-color-restore.zip   Xiaohongshu mini tool
 *   node scripts/build.mjs weapp      copies core/ into weapp/miniprogram/core/       WeChat mini program
 *
 * The web and xhs targets share web/index.html and web/assets/; they differ only in which
 * web/platforms/<target>.js becomes assets/platform.js.
 */
import { cpSync, existsSync, mkdirSync, rmSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CORE = join(ROOT, "core");
const WEB = join(ROOT, "web");
const DIST = join(ROOT, "dist");
const CORE_FILES = ["i18n.js", "restore.js", "compare.js"];
const GENERATED = "/* Generated by scripts/build.mjs from core/. Edit the file in core/, not this copy. */\n";

const skipJunk = (source) => !/(^|[\\/])(\.DS_Store|Thumbs\.db)$/.test(source);

function buildH5(target, { includeLicenses }) {
  const platformFile = join(WEB, "platforms", `${target}.js`);
  if (!existsSync(platformFile)) throw new Error(`missing ${platformFile}`);
  const out = join(DIST, target);
  rmSync(out, { recursive: true, force: true });
  mkdirSync(join(out, "assets", "core"), { recursive: true });

  cpSync(join(WEB, "index.html"), join(out, "index.html"));
  cpSync(join(WEB, "assets"), join(out, "assets"), { recursive: true, filter: skipJunk });
  for (const file of CORE_FILES) cpSync(join(CORE, file), join(out, "assets", "core", file));
  cpSync(platformFile, join(out, "assets", "platform.js"));
  if (includeLicenses) cpSync(join(WEB, "licenses"), join(out, "licenses"), { recursive: true, filter: skipJunk });
  console.log(`built ${target}: ${out}`);
  return out;
}

function zipDirectory(directory, zipPath) {
  rmSync(zipPath, { force: true });
  // Zip the directory's contents, not the directory, so index.html sits at the zip root.
  execFileSync("zip", ["-r", "-X", "-q", zipPath, ".", "-x", "*.DS_Store"], { cwd: directory, stdio: "inherit" });
  console.log(`zipped: ${zipPath}`);
}

function buildWeb() {
  buildH5("web", { includeLicenses: true });
}

function buildXhs() {
  // The mini tool zip may not contain .txt files, so the font licence stays out (it is in the font metadata).
  const out = buildH5("xhs", { includeLicenses: false });
  zipDirectory(out, join(DIST, "underwater-color-restore.zip"));
}

function buildWeapp() {
  const target = join(ROOT, "weapp", "miniprogram", "core");
  mkdirSync(target, { recursive: true });
  for (const file of CORE_FILES) {
    writeFileSync(join(target, file), GENERATED + readFileSync(join(CORE, file), "utf8"));
  }
  console.log(`synced core into: ${target} (${readdirSync(target).join(", ")})`);
}

const TARGETS = {
  web: { build: buildWeb, present: () => existsSync(join(WEB, "platforms", "web.js")) },
  xhs: { build: buildXhs, present: () => existsSync(join(WEB, "platforms", "xhs.js")) },
  weapp: { build: buildWeapp, present: () => existsSync(join(ROOT, "weapp", "miniprogram", "app.json")) }
};

const requested = process.argv.slice(2);
const names = requested.length && requested[0] !== "all"
  ? requested
  : Object.keys(TARGETS).filter((name) => TARGETS[name].present());

for (const name of names) {
  if (!TARGETS[name]) {
    console.error(`unknown target "${name}". Use one of: ${Object.keys(TARGETS).join(", ")}, all`);
    process.exit(1);
  }
  TARGETS[name].build();
}
